"""Static-policy failure table: where each fixed/schedule policy loses.

Four regimes (link stress x backbone quality) x four policies (fixed r4, fixed
r16, SA anneal, FedRAS). Each cell reports, against the best of the four
policies in that cell: the accuracy gap in percentage points, delivered
capacity (dc_meas, terminal rounds 30-39) as percent of the best, and timely
ratio as percent of the best. A static policy that is optimal in one regime
pays elsewhere; FedRAS is never the clear loser.

Reads outputs/journal_stats/delivered_capacity_terminal.csv (complete runs
only; in-flight families are absent and simply drop out). Writes
outputs/journal_stats/static_failure_table.tex and prints the matrix.
Writes nothing else.
"""
import os

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STATS = os.path.join(ROOT, 'outputs', 'journal_stats')

REGIMES = [('cifar10', 'nominal / strong backbone'),
           ('cifar10_dl0.1', 'stress / strong backbone'),
           ('weak', 'nominal / weak backbone'),
           ('weak_dl0.1', 'stress / weak backbone')]
# a regime may draw policies from several run families (SA runs live in sa_strong*)
ALIAS = {'cifar10': ['cifar10', 'sa_strong'],
         'cifar10_dl0.1': ['cifar10_dl0.1', 'sa_strong_dl0.1']}
POLICIES = [('FedLoRA_r4', 'Fixed $r=4$'),
            ('FedLoRA_r16', 'Fixed $r=16$'),
            ('SA_rank', 'SA anneal (link-oblivious)'),
            ('Adaptive_rank', 'FedRAS')]
OUTCOMES = ['acc', 'dc_meas', 'timely']


def main():
    t = pd.read_csv(os.path.join(STATS, 'delivered_capacity_terminal.csv'))
    cells = {}
    for fam, label in REGIMES:
        d = t[t.family.isin(ALIAS.get(fam, [fam])) & t.method.isin([p for p, _ in POLICIES])]
        have = [m for m, _ in POLICIES if m in set(d.method)]
        if 'Adaptive_rank' not in have or len(have) < 3:
            continue  # regime not landed enough yet
        dd = d[d.method.isin(have)]
        best = {o: dd[o].max() for o in OUTCOMES}
        cc = {}
        for m in have:
            row = dd[dd.method == m].iloc[0]
            cc[m] = (-(best['acc'] - row.acc) * 100,
                     100 * row.dc_meas / best['dc_meas'],
                     100 * row.timely / best['timely'])
        cells[fam] = (label, best, cc)

    lines = ['% auto-generated by print_static_failure_table.py -- do not edit by hand',
             '\\begin{tabular}{lcccc}', '\\toprule',
             'Policy & ' + ' & '.join(lbl for _, (lbl, _, _) in
                                      [(f, cells[f]) for f, _ in REGIMES if f in cells]) + ' \\\\',
             '\\midrule']
    print('cell format: accuracy gap (pp vs best) / delivered capacity (% of best) / timely (% of best)')
    for m, name in POLICIES:
        row = [name]
        for fam, _ in REGIMES:
            if fam not in cells or m not in cells[fam][2]:
                continue
            dacc, dcp, dtp = cells[fam][2][m]
            row.append(f'{dacc:+.1f}\\,pp / {dcp:.0f}\\% / {dtp:.0f}\\%')
            print(f'{fam:16s} {name:28s} acc {dacc:+.2f}pp  dc {dcp:5.1f}%  timely {dtp:5.1f}%')
        if len(row) > 1:
            lines.append(' & '.join(row) + ' \\\\')
    lines += ['\\bottomrule', '\\end{tabular}']
    out = os.path.join(STATS, 'static_failure_table.tex')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f'\nwrote {out}')


if __name__ == '__main__':
    main()
